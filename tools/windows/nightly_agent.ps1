<# The nightly ENGINE AGENT: pull harness, branch, let a headless Claude Code session improve the engine
   against the scorer for N hours, verify its claim independently, then tune knobs around whatever it
   landed. Everything it prints goes to results\nightly\<date>-agent.log; the night's artefacts go to
   results\agent\<date>\ (prompt.md, agent.out, agent.err, gate_verify.json, NIGHT.md, the agent's REPORT.md).
   Exit codes: 0 ok, 2 agent/search crash, 3 preflight failed, 4 the agent's work failed verification.
   Requires Claude Code on PATH and signed in (docs\HANDOFF_windows_agent_setup.md). #>
param(
  [double]$Hours = 4,            # agent wall-clock budget
  [double]$SearchHours = 1.5,    # knob search after an accepted night (0 = skip)
  [int]$Patience = 300,
  [string]$Model = "",           # e.g. "opus"; empty = Claude Code's default
  [double]$MaxBudgetUsd = 0,     # 0 = no cap
  [switch]$Push                  # push the agent branch to origin for review from another machine
)
$ErrorActionPreference = "Continue"
$root = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
Set-Location $root
$date = Get-Date -Format yyyyMMdd
New-Item -ItemType Directory -Force -Path results\nightly, "results\agent\$date" | Out-Null
$night = Join-Path $root "results\agent\$date"
$log = "results\nightly\$(Get-Date -Format yyyyMMdd-HHmm)-agent.log"
Start-Transcript -Path $log | Out-Null
$py = ".\.venv\Scripts\python.exe"
$exit = 0

$awake = $false
try {
  Add-Type -Name Power -Namespace LiveReact -MemberDefinition @"
[DllImport("kernel32.dll", SetLastError = true)]
public static extern uint SetThreadExecutionState(uint esFlags);
"@
  [void][LiveReact.Power]::SetThreadExecutionState(0x80000000 -bor 0x00000001)
  $awake = $true
  Write-Host "power: system-required request held for this run"
} catch { Write-Host "power: could not hold a wake request ($($_.Exception.Message))" }

function Fail($code, $msg) { Write-Host "PREFLIGHT FAILED: $msg"; $script:exit = $code }

try {
  # ---- preflight ---------------------------------------------------------------------------------
  $dirty = (git status --porcelain 2>$null | Where-Object { $_ -notmatch '^\?\?' })
  if ($dirty) { Fail 3 "working tree has local changes:`n$($dirty -join "`n")"; exit 3 }
  git fetch origin 2>&1 | Out-Null
  git checkout harness 2>&1 | Out-Null
  $pull = git pull --ff-only origin harness 2>&1
  $pull | ForEach-Object { Write-Host $_ }
  if ($LASTEXITCODE -ne 0) { Fail 3 "git pull --ff-only did not succeed"; exit 3 }
  $base = (git rev-parse --short HEAD).Trim()
  Write-Host ("code: " + (git log --oneline -1))
  & $py -m pip install --quiet -e ".[sim,dev]" 2>&1 | Out-Null
  & $py -m pytest -q tests\test_harness_determinism.py 2>&1 | Select-Object -Last 1
  if ($LASTEXITCODE -ne 0) { Fail 3 "determinism test"; exit 3 }
  $claudeVer = (& claude --version 2>&1 | Select-Object -First 1)
  if ($LASTEXITCODE -ne 0 -or -not $claudeVer) { Fail 3 "claude CLI not found on PATH"; exit 3 }
  Write-Host "claude: $claudeVer"

  # ---- branch ------------------------------------------------------------------------------------
  $branch = "agent/$date"
  $k = 2
  while (git rev-parse --verify --quiet $branch 2>$null) { $branch = "agent/$date-$k"; $k++ }
  git checkout -b $branch 2>&1 | Out-Null
  Write-Host "branch: $branch (from harness $base)"

  # ---- prompt ------------------------------------------------------------------------------------
  $start = Get-Date
  $deadline = $start.AddHours($Hours)
  $header = @"
# Runtime header (generated by nightly_agent.ps1)
- date: $date
- branch: $branch (created from harness @ $base)
- repo: $root  (Windows; python = .\.venv\Scripts\python.exe; tests: .\.venv\Scripts\python -m pytest -q)
- start: $($start.ToString('yyyy-MM-dd HH:mm'))   deadline: $($deadline.ToString('yyyy-MM-dd HH:mm'))  (hard kill at the deadline)
- night folder for your report, gate outputs and study scripts: results\agent\$date\
- the knob search runs AFTER you, by the orchestrator; do not run it yourself

"@
  $brief = Get-Content docs\AGENT_BRIEF.md -Raw
  $promptPath = Join-Path $night "prompt.md"
  Set-Content -Path $promptPath -Value ($header + $brief) -Encoding UTF8

  # ---- run the agent -----------------------------------------------------------------------------
  $outPath = Join-Path $night "agent.out"
  $errPath = Join-Path $night "agent.err"
  $flags = "-p --permission-mode bypassPermissions --output-format text --no-session-persistence " +
           "--disallowedTools `"Bash(git push:*)`" `"Bash(git checkout harness*)`" `"Bash(git checkout main*)`" `"Bash(git merge:*)`" `"Bash(git rebase:*)`" `"Bash(pip install:*)`" `"Bash(python tools/loop/search.py:*)`""
  if ($Model) { $flags += " --model $Model" }
  if ($MaxBudgetUsd -gt 0) { $flags += " --max-budget-usd $MaxBudgetUsd" }
  $cmd = "type `"$promptPath`" | claude $flags > `"$outPath`" 2> `"$errPath`""
  Write-Host "agent: starting at $($start.ToString('HH:mm')), budget $Hours h"
  $proc = Start-Process -FilePath "cmd.exe" -ArgumentList "/c", $cmd -WorkingDirectory $root -PassThru -WindowStyle Hidden
  $finished = $proc.WaitForExit([int]($Hours * 3600 * 1000))
  if (-not $finished) {
    Write-Host "agent: deadline reached, killing the session tree"
    & taskkill /T /F /PID $proc.Id 2>&1 | Out-Null
    $agentStatus = "killed at deadline"
  } else { $agentStatus = "exited $($proc.ExitCode)" }
  Write-Host "agent: $agentStatus after $([int]((Get-Date) - $start).TotalMinutes) min"
  if (Test-Path $errPath) { Get-Content $errPath | Select-Object -Last 15 | ForEach-Object { Write-Host "agent.err: $_" } }

  # ---- verify independently ----------------------------------------------------------------------
  $left = (git status --porcelain 2>$null | Where-Object { $_ -notmatch '^\?\?' })
  if ($left) {
    Write-Host "agent left uncommitted changes; stashing them as 'agent-$date-leftovers'"
    git stash push -u -m "agent-$date-leftovers" 2>&1 | Out-Null
  }
  $commits = [int](git rev-list --count "harness..HEAD" 2>$null)
  Write-Host "commits on $branch : $commits"
  git log --oneline "harness..HEAD" 2>$null | ForEach-Object { Write-Host "  $_" }
  $tests = "skipped"; $gate = "NO-CHANGE"
  if ($commits -gt 0) {
    $pt = & $py -m pytest -q 2>&1
    $summary = ($pt | Select-Object -Last 1)
    Write-Host "pytest: $summary"
    # exactly the 3 known spec-gap failures are allowed
    $failed = 0; if ($summary -match '(\d+) failed') { $failed = [int]$Matches[1] }
    $knownOnly = ($pt | Where-Object { $_ -match '^FAILED' } | Where-Object { $_ -notmatch 'test_spec_conformance_gaps' }).Count -eq 0
    $tests = if ($failed -le 3 -and $knownOnly) { "ok" } else { "FAIL" }
    git show "harness:results/baseline/evaluation.json" > (Join-Path $night "baseline_harness.json")
    & $py tools\agent\gate_head.py --baseline (Join-Path $night "baseline_harness.json") --out (Join-Path $night "gate_verify.json") 2>&1 | Select-Object -Last 25
    $gate = if ($LASTEXITCODE -eq 0) { "ACCEPT" } elseif ($LASTEXITCODE -eq 1) { "REJECT" } else { "ERROR" }
    Write-Host "independent gate vs harness baseline: $gate ; tests: $tests"
    if ($gate -ne "ACCEPT" -or $tests -ne "ok") { $exit = 4 }
  }

  # ---- knob search around the new code (only when the night is good) -----------------------------
  $searchNote = "skipped"
  if ($commits -gt 0 -and $gate -eq "ACCEPT" -and $tests -eq "ok" -and $SearchHours -gt 0) {
    Write-Host "search: $SearchHours h around $branch"
    & $py tools\loop\search.py --hours $SearchHours --patience $Patience --out "results\search\$date-agent"
    if ($LASTEXITCODE -eq 2) { $exit = 2 }
    $sm = "results\search\$date-agent\summary.md"
    if (Test-Path $sm) { $searchNote = (Get-Content $sm | Select-Object -First 6) -join "`n" ; Write-Host $searchNote }
  }

  # ---- morning note ------------------------------------------------------------------------------
  $report = Join-Path $night "REPORT.md"
  $reportHead = if (Test-Path $report) { (Get-Content $report | Select-Object -First 60) -join "`n" } else { "(the agent wrote no REPORT.md)" }
  $nightMd = @"
# Night $date — $branch

- agent: $agentStatus; commits: $commits; tests: $tests; independent gate vs harness ($base): $gate
- knob search:
$searchNote

## Commits
$((git log --oneline "harness..HEAD" 2>$null) -join "`n")

## Agent report (head)
$reportHead
"@
  Set-Content -Path (Join-Path $night "NIGHT.md") -Value $nightMd -Encoding UTF8
  & $py tools\agent\record_night.py --date $date --branch $branch --commits $commits --gate $gate --tests $tests --note "orchestrator: $agentStatus" | Out-Null
  if ($Push -and $commits -gt 0) { git push -u origin $branch 2>&1 | ForEach-Object { Write-Host $_ } }
  git checkout harness 2>&1 | Out-Null
  Write-Host "done: $branch commits=$commits gate=$gate tests=$tests -> $night\NIGHT.md"
  exit $exit
} finally {
  if ($awake) { try { [void][LiveReact.Power]::SetThreadExecutionState(0x80000000) } catch {} }
  Stop-Transcript | Out-Null
}
