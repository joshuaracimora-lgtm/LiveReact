"""Roadmap item 26: the manual page finder (fixtures/manual_reader/extract.py) on a small PDF
generated by the test itself."""
from __future__ import annotations

import json

import pytest

from livereact.fixtures.manual_reader import extract


def make_pdf(path, pages: list[str]) -> None:
    """A minimal valid PDF, one Helvetica text page per string ('' = an image-only page)."""
    objs: list[bytes] = []
    n = len(pages)
    font_id = 3 + 2 * n
    kids = " ".join(f"{3 + 2 * i} 0 R" for i in range(n))
    objs.append(b"<< /Type /Catalog /Pages 2 0 R >>")
    objs.append(f"<< /Type /Pages /Kids [{kids}] /Count {n} >>".encode())
    for i, text in enumerate(pages):
        lines = [ln.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)") for ln in text.split("\n")]
        ops = "BT /F1 11 Tf 14 TL 50 780 Td " + " ".join(f"({ln}) Tj T*" for ln in lines) + " ET" if text else ""
        stream = ops.encode("latin-1")
        objs.append(f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents {4 + 2 * i} 0 R "
                    f"/Resources << /Font << /F1 {font_id} 0 R >> >> >>".encode())
        objs.append(b"<< /Length %d >>\nstream\n" % len(stream) + stream + b"\nendstream")
    objs.append(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>")
    out = bytearray(b"%PDF-1.4\n")
    offsets = []
    for i, body in enumerate(objs):
        offsets.append(len(out))
        out += f"{i + 1} 0 obj\n".encode() + body + b"\nendobj\n"
    xref = len(out)
    out += f"xref\n0 {len(objs) + 1}\n0000000000 65535 f \n".encode()
    for off in offsets:
        out += f"{off:010d} 00000 n \n".encode()
    out += f"trailer\n<< /Size {len(objs) + 1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n".encode()
    path.write_bytes(bytes(out))


COVER = "Thank you for purchasing this product.\nPlease read this manual carefully before use."
SAFETY = "Safety instructions\nKeep away from water. Do not look into the beam.\nDisconnect power before cleaning."
CHART = ("DMX channel chart (7CH mode)\nCH1 Dimmer 000-255\nCH2 Red 000-255\nCH3 Green 000-255\n"
         "CH4 Blue 000-255\nCH5 Strobe 000-009 off, 010-255 slow to fast\nCH6 Macro 000-255\nCH7 Speed 000-255")
CHART2 = "DMX address setting\nChannel mode: 3CH or 7CH\nCH1 Red 0-255\nCH2 Green 0-255\nCH3 Blue 0-255"


@pytest.fixture
def manual(tmp_path):
    p = tmp_path / "manual.pdf"
    make_pdf(p, [COVER, SAFETY, CHART, "", CHART2, SAFETY])
    return p


def test_score_text_prefers_charts():
    assert extract.score_text(CHART) > extract.score_text(CHART2) > extract.score_text(SAFETY)
    assert extract.score_text(COVER) == 0
    assert extract.score_text("Rated 100-240 V, 50-60 Hz") < 4.0      # ranges alone are not a chart


def test_pages_are_scored_and_scanned_flagged(manual):
    pages = extract.score_pages(manual)
    assert [p.number for p in pages] == [1, 2, 3, 4, 5, 6]
    assert [p.scanned for p in pages] == [False, False, False, True, False, False]
    best = max(pages, key=lambda p: p.score)
    assert best.number == 3


def test_find_writes_trimmed_pdf_with_page_map(manual, tmp_path):
    from pypdf import PdfReader
    res = extract.find_dmx_pages(manual, manuals_dir=tmp_path / "manuals")
    assert res.best == [3, 5]
    assert res.scanned == [4]
    assert res.sha256 == extract.sha256_of(manual)
    assert res.trimmed_pdf == tmp_path / "manuals" / res.sha256 / "trimmed.pdf"
    trimmed = PdfReader(str(res.trimmed_pdf))
    assert len(trimmed.pages) == 2
    assert "CH5 Strobe" in trimmed.pages[0].extract_text()
    assert res.page_map == {1: 3, 2: 5}
    meta = json.loads((res.trimmed_pdf.parent / "pages.json").read_text(encoding="utf-8"))
    assert meta["page_map"] == {"1": 3, "2": 5} and meta["scanned"] == [4]


def test_at_most_fifteen_pages(tmp_path):
    p = tmp_path / "big.pdf"
    make_pdf(p, [CHART] * 20)
    res = extract.find_dmx_pages(p, manuals_dir=tmp_path / "m")
    assert len(res.best) == extract.MAX_PAGES == 15
    assert res.best == list(range(1, 16))


def test_a_scanned_manual_sends_its_image_pages(tmp_path):
    p = tmp_path / "scan.pdf"
    make_pdf(p, [COVER, "", "", SAFETY])
    res = extract.find_dmx_pages(p, manuals_dir=tmp_path / "m")
    assert res.best == [2, 3] and res.scanned == [2, 3]


def test_nothing_useful_writes_no_trimmed_pdf(tmp_path):
    p = tmp_path / "plain.pdf"
    make_pdf(p, [COVER, SAFETY])
    res = extract.find_dmx_pages(p, manuals_dir=tmp_path / "m")
    assert res.best == [] and res.trimmed_pdf is None


def test_default_folder_is_the_user_manuals_folder(manual, tmp_path, monkeypatch):
    from livereact import userdata
    monkeypatch.setenv("LIVEREACT_HOME", str(tmp_path / "home"))
    res = extract.find_dmx_pages(manual)
    assert res.trimmed_pdf.parent == userdata.paths().manuals / res.sha256
